using Versio.Core.Bindings;
using Xunit;

namespace Versio.Core.Tests.Bindings;

/// <summary>
/// Which tracked project a changed file belongs to.
/// </summary>
/// <remarks>
/// <para>
/// The question behind this is "does acting on this file concern a mirror?" — discarding a
/// file inside an export tree releases that binding's direction lock (plan §6.5), while
/// discarding an unrelated README must release nothing. A wrong answer here therefore either
/// leaves a lock held that nobody can find the reason for, or drops one that was holding real
/// work.
/// </para>
/// <para>
/// The cases below are not hypothetical. A bare <c>StartsWith</c> is exactly the bug the fake
/// filesystem had — <c>plc/A.project</c> enumerated as part of its own export tree
/// <c>plc/A</c> — and it is the first thing anybody writes here.
/// </para>
/// </remarks>
public sealed class BindingOwnershipTests
{
    private static ProjectBinding Binding(string id, string exportPath, bool enabled = true) =>
        new()
        {
            Id = id,
            ProjectPath = exportPath + ".project",
            ExportPath = exportPath,
            Enabled = enabled,
        };

    private static readonly ProjectBinding[] Two =
    [
        Binding("b-machine", "plc/Machine"),
        Binding("b-machine2", "plc/Machine2"),
    ];

    [Theory]
    [InlineData("plc/Machine/Main.st", "b-machine")]
    [InlineData("plc/Machine/Device/Plc Logic/Application/Main.st", "b-machine")]
    [InlineData("plc/Machine/_manifest.json", "b-machine")]
    [InlineData("plc/Machine2/Main.st", "b-machine2")]
    public void A_file_inside_an_export_tree_belongs_to_its_binding(string path, string expected)
    {
        Assert.Equal(expected, BindingConventions.OwnerOf(Two, path)?.Id);
    }

    [Theory]
    [InlineData("plc/Machine.project")]      // the project beside its own export tree
    [InlineData("plc/MachineOther/Main.st")] // a sibling sharing the prefix
    [InlineData("README.md")]
    [InlineData("docs/plc/Machine/Main.st")] // same name, different place
    [InlineData("")]
    public void A_file_outside_every_export_tree_belongs_to_none(string path)
    {
        Assert.Null(BindingConventions.OwnerOf(Two, path));
    }

    [Fact]
    public void The_export_directory_itself_is_not_a_file_inside_it()
    {
        // The callers are asking which binding owns a file. The directory is not one, and
        // answering otherwise would make a change to a path that cannot exist release a lock.
        Assert.Null(BindingConventions.OwnerOf(Two, "plc/Machine"));
        Assert.Null(BindingConventions.OwnerOf(Two, "plc/Machine/"));
    }

    [Fact]
    public void A_nested_binding_wins_over_the_one_that_contains_it()
    {
        // Unusual but legal: an export tree inside another repository folder that is itself
        // a binding. Answering with the outer one would release the wrong lock, and "first in
        // the config" is not a rule anybody could predict.
        ProjectBinding[] nested =
        [
            Binding("b-outer", "plc"),
            Binding("b-inner", "plc/Machine"),
        ];

        Assert.Equal("b-inner", BindingConventions.OwnerOf(nested, "plc/Machine/Main.st")?.Id);
        Assert.Equal("b-outer", BindingConventions.OwnerOf(nested, "plc/Other/Main.st")?.Id);
    }

    [Fact]
    public void A_disabled_binding_owns_nothing()
    {
        // It is not syncing, so it holds no lock to release. Treating it as an owner would
        // send a release to a binding the orchestrator is not tracking, which it logs as a
        // warning — noise generated by us, about us.
        ProjectBinding[] off = [Binding("b-off", "plc/Machine", enabled: false)];

        Assert.Null(BindingConventions.OwnerOf(off, "plc/Machine/Main.st"));
    }

    [Theory]
    [InlineData("plc\\Machine\\Main.st")]
    [InlineData("/plc/Machine/Main.st")]
    public void Separators_and_leading_slashes_do_not_change_the_answer(string path)
    {
        // git reports forward slashes, the filesystem hands back backslashes, and the panel
        // has had both. A path that fails to match because of its separator would drop the
        // lock release silently.
        Assert.Equal("b-machine", BindingConventions.OwnerOf(Two, path)?.Id);
    }

    [Fact]
    public void Case_does_not_change_the_answer_on_a_windows_path()
    {
        // Windows only, by decision (plan §13.7), and the same file really can arrive spelled
        // two ways — git's own output preserves what was recorded, not what is on disk.
        Assert.Equal("b-machine", BindingConventions.OwnerOf(Two, "PLC/MACHINE/Main.st")?.Id);
    }
}
