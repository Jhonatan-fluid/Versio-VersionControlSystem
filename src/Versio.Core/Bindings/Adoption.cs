using Versio.Core.Plc;

namespace Versio.Core.Bindings;

/// <summary>Whether a discovered project may be tracked, and why not if it may not.</summary>
/// <remarks>
/// Every value is something the panel must be able to explain in one sentence. A greyed-out
/// button with no reason is the failure mode this enum exists to prevent.
/// </remarks>
public enum AdoptionVerdict
{
    /// <summary>Nothing objects. A binding is ready to be written.</summary>
    Ready,

    /// <summary>The path is not a project file this toolchain recognises.</summary>
    NotAProject,

    /// <summary>An absolute path. Bindings are stored repo-relative so the repository can be
    /// cloned or moved without every path breaking.</summary>
    NotRepoRelative,

    /// <summary>A template. Adopting one creates a binding that exports the template into
    /// its own tree (plan R28).</summary>
    IsTemplate,

    /// <summary>A binding already covers this project.</summary>
    AlreadyBound,

    /// <summary>Another binding already names this file as its template.</summary>
    BoundAsTemplate,

    /// <summary>The conventional export directory belongs to a different binding.</summary>
    ExportPathTaken,

    /// <summary>Excluded by an <c>ignore</c> glob in <c>repo.json</c>.</summary>
    Ignored,
}

/// <summary>The answer to "can this project be tracked", with the binding to write if it can.</summary>
public readonly record struct AdoptionDecision(
    AdoptionVerdict Verdict,
    string Explanation,
    ProjectBinding? Binding)
{
    public bool CanAdopt => Verdict == AdoptionVerdict.Ready && Binding is not null;

    private static AdoptionDecision No(AdoptionVerdict verdict, string why) =>
        new(verdict, why, null);

    internal static AdoptionDecision NotAProject(string why) =>
        No(AdoptionVerdict.NotAProject, why);

    internal static AdoptionDecision NotRepoRelative(string why) =>
        No(AdoptionVerdict.NotRepoRelative, why);

    internal static AdoptionDecision IsTemplate(string why) =>
        No(AdoptionVerdict.IsTemplate, why);

    internal static AdoptionDecision AlreadyBound(string why) =>
        No(AdoptionVerdict.AlreadyBound, why);

    internal static AdoptionDecision BoundAsTemplate(string why) =>
        No(AdoptionVerdict.BoundAsTemplate, why);

    internal static AdoptionDecision ExportPathTaken(string why) =>
        No(AdoptionVerdict.ExportPathTaken, why);

    internal static AdoptionDecision Ignored(string why) =>
        No(AdoptionVerdict.Ignored, why);
}

/// <summary>
/// Decides whether a discovered project can be adopted, and what binding to write for it.
/// </summary>
/// <remarks>
/// <para>
/// Adoption is the one irreversible-feeling step in the tool: it commits a mapping into
/// <c>repo.json</c> that every teammate will pull, and the first export that follows writes
/// a whole directory tree. So the refusals live here, pure and unit tested, rather than as
/// <c>if</c> statements scattered through a view model where they cannot be exercised.
/// </para>
/// <para>
/// <b>The checks are ordered by cost of being wrong, not by likelihood.</b> The template
/// guards come before the "already tracked" guard because adopting a template produces a
/// binding that exports a template into its own tree — nonsense that is genuinely confusing
/// to unpick — while a duplicate adopt is merely a no-op the user can see.
/// </para>
/// </remarks>
public static class Adoption
{
    /// <summary>Plan the adoption of one discovered project.</summary>
    /// <param name="projectPath">Repo-relative path, as the scanner reports it.</param>
    /// <param name="config">Current contents of <c>repo.json</c>.</param>
    /// <param name="format">The vendor's conventions.</param>
    /// <param name="bindingId">Generated by the caller: the id is the identity and must
    /// outlive every path in the binding, so it is never derived from one.</param>
    /// <param name="profile">Toolchain profile to pin, when one has been resolved.</param>
    /// <param name="otherProjects">
    /// Every project the scan found, tracked or not, repo-relative. A root that would contain
    /// one of them is refused: see the loop below. Null when the caller has no scan — the
    /// infrastructure gate (<c>RepoSetup.AdoptAsync</c>) scans for itself then, so nothing
    /// reaches this with the answer missing.
    /// </param>
    public static AdoptionDecision Plan(
        string projectPath,
        RepoConfig config,
        IPlcProjectFormat format,
        string bindingId,
        string? profile = null,
        IReadOnlyCollection<string>? otherProjects = null)
    {
        var raw = projectPath.Replace('\\', '/');

        if (string.IsNullOrWhiteSpace(raw))
        {
            return AdoptionDecision.NotAProject("no path was supplied");
        }

        // Checked BEFORE the leading separator is trimmed, or "/srv/repo/x.project" would be
        // quietly rewritten into a plausible repo-relative path instead of being refused.
        // Rooted paths survive one session and break on the next clone, and the orchestrator
        // will use one quite happily — which is exactly why it is stopped here.
        if (Path.IsPathRooted(raw) || raw.Contains(':'))
        {
            return AdoptionDecision.NotRepoRelative(
                $"'{raw}' is an absolute path; bindings record repository-relative paths " +
                "so a clone or a move does not break them");
        }

        var path = Normalize(raw);

        var extension = Path.GetExtension(path);
        if (!format.ProjectExtensions.Contains(extension, StringComparer.OrdinalIgnoreCase))
        {
            return AdoptionDecision.NotAProject(
                $"'{path}' is not a {format.DisplayName} project " +
                $"({string.Join(", ", format.ProjectExtensions)})");
        }

        if (format.IsTemplate(path))
        {
            return AdoptionDecision.IsTemplate(
                $"'{path}' is a template, not a working project; tracking it would export " +
                "the template into its own tree");
        }

        // Disabled bindings are checked too. A disabled binding still owns its paths, and
        // adopting around it would leave two entries competing for one export directory.
        foreach (var binding in config.Bindings)
        {
            if (binding.TemplatePath is { } template &&
                string.Equals(Normalize(template), path, StringComparison.OrdinalIgnoreCase))
            {
                return AdoptionDecision.BoundAsTemplate(
                    $"'{path}' is already used as the template for binding '{binding.Id}'");
            }
        }

        var existing = config.Bindings.FirstOrDefault(b =>
            string.Equals(Normalize(b.ProjectPath), path, StringComparison.OrdinalIgnoreCase));
        if (existing is not null)
        {
            return AdoptionDecision.AlreadyBound(
                existing.Enabled
                    ? $"'{path}' is already tracked as binding '{existing.Id}'"
                    : $"'{path}' is bound as '{existing.Id}' but disabled; re-enable it " +
                      "rather than adopting it a second time");
        }

        if (PathGlob.Matches(path, config.Ignore))
        {
            return AdoptionDecision.Ignored(
                $"'{path}' matches an ignore rule in repo.json; remove the rule to track it");
        }

        var exportPath = Normalize(format.ConventionalExportPath(path));
        foreach (var other in config.Bindings)
        {
            var otherExport = Normalize(other.ExportPath);
            var otherProject = Normalize(other.ProjectPath);

            if (string.Equals(otherExport, exportPath, StringComparison.OrdinalIgnoreCase))
            {
                return AdoptionDecision.ExportPathTaken(
                    $"'{exportPath}' is already the export directory for binding " +
                    $"'{other.Id}'; two projects exporting into one tree would overwrite " +
                    "each other silently");
            }

            // Not only the same directory: one inside the other, in either direction, and a
            // project file inside the other's export tree. An export replaces its whole
            // directory — the new tree is written beside the old one and swapped in — so a
            // root that contains another binding's export root or project file deletes it
            // on the next export, and a root inside another's is deleted by that one's.
            // `A.project` with `A/B.project` was accepted and did exactly that (the
            // 2026-10-25 review's fifth round, item 2). Checked here, at the one gate every
            // adoption passes, rather than in the export, where the only answer left would
            // be to refuse a sync somebody had already been promised.
            if (IsUnder(exportPath, otherExport) || IsUnder(otherExport, exportPath))
            {
                return AdoptionDecision.ExportPathTaken(
                    $"'{exportPath}' and binding '{other.Id}''s export directory " +
                    $"'{otherExport}' would be one inside the other; an export replaces its " +
                    "whole directory, so one would delete the other's tree");
            }

            if (IsUnder(otherProject, exportPath))
            {
                return AdoptionDecision.ExportPathTaken(
                    $"'{exportPath}' would contain the project file of binding '{other.Id}' " +
                    $"('{otherProject}'); an export replaces its whole directory and would " +
                    "delete that project");
            }

            if (IsUnder(path, otherExport))
            {
                return AdoptionDecision.ExportPathTaken(
                    $"'{path}' sits inside the export directory of binding '{other.Id}' " +
                    $"('{otherExport}'); an export of that project replaces its whole " +
                    "directory and would delete this one");
            }
        }

        // The projects that are NOT tracked, too. The check above reads the bindings, and on
        // a fresh scan there are none yet: A.project was adopted first, A/B.project was then
        // refused for sitting inside A's export root — and A's export deleted it all the same,
        // because the refusal protected the inner project from being tracked, not from being
        // overwritten (the 2026-10-25 review's sixth round, item 1, P1, after the fifth's item
        // 2 closed the tracked half). So a root that would contain any project the scan found
        // is refused, whichever is adopted first; the inner one adopts on its own, and the
        // outer one waits for the inner to be moved. The outer, not the inner, because the
        // outer is the one whose export destroys.
        foreach (var discovered in otherProjects ?? [])
        {
            var other = Normalize(discovered);
            if (!string.Equals(other, path, StringComparison.OrdinalIgnoreCase)
                && IsUnder(other, exportPath))
            {
                return AdoptionDecision.ExportPathTaken(
                    $"'{exportPath}' would contain '{other}', a project that is not tracked; an " +
                    "export replaces its whole directory and would delete that project. Move it " +
                    "out of the way, or track it on its own and leave this one untracked");
            }
        }

        return new AdoptionDecision(
            AdoptionVerdict.Ready,
            $"'{path}' will export to '{exportPath}'",
            OrphanScanner.ProposeBinding(path, bindingId, profile, format));
    }

    private static string Normalize(string p) => p.Replace('\\', '/').TrimStart('/');

    /// <summary>Whether <paramref name="path"/> is strictly beneath <paramref name="root"/>: a
    /// directory boundary, so <c>plc/AB</c> is not under <c>plc/A</c>.</summary>
    private static bool IsUnder(string path, string root) =>
        path.StartsWith(root.TrimEnd('/') + "/", StringComparison.OrdinalIgnoreCase);
}
